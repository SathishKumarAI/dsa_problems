// Emit `src/data/demos.ts` — one Python argument list per problem, so the Run
// button on a code block can actually print something.
//
// THE PROBLEM THIS SOLVES, measured in a real browser on 2026-09-15. Every
// ```python fence in a teaching document is a function DEFINITION: no `print`,
// no top-level call. Pressing Run on `balanced-brackets` gave "exit 0 · 5 ms"
// and "the script printed nothing" — three of the four buttons on that page did
// nothing a reader could see. Only the full script at the foot, which has its
// own `main()`, printed anything at all.
//
// A definition has nothing to print. So the Run button appends a call, and this
// file is where the argument comes from: `scripts/localsmith/vectors.mjs`, the
// same inputs the differential runner drives Java and C++ with. They are
// already known to work against the Python, which is the whole reason to use
// them rather than parse an example out of prose.
//
// A linked list or a tree is built with the same `__mklist` / `__mktree` the
// driver uses — they ride along in `src/lib/py-preamble.ts`, copied verbatim
// from that file — so those problems get a one-line call too. A `shape: "class"`
// problem does not: its entry point is a class to instantiate against a script
// of operations, which is a different driver and not one line.
//
// GENERATED, committed, and guarded: `src/data/demos.test.ts` rebuilds it in
// memory and fails if the checked-in copy has drifted.
//
// Run:  node scripts/gen-demos.mjs
//       node scripts/gen-demos.mjs --check   # exit 1 if stale, writes nothing

import { readFileSync, writeFileSync } from "node:fs"
import { VECTORS } from "./localsmith/vectors.mjs"
import { PROBLEMS } from "../src/data/index.ts"

const check = process.argv.includes("--check")
const OUT = "src/data/demos.ts"

// WHICH CASE. The first vector used to be it, and the vectors put their
// nastiest case first on purpose — sorted-pair-sum's is `[2], 4`, one element,
// written to catch `i <= j`. So every Run on that page printed `[]`, under a
// page whose statement, walkthrough and every worked example use
// `[1, 3, 6, 9], 12`. A reader who has just traced that by hand presses Run and
// gets an empty list for an input they cannot see. Measured 2026-10-17.
//
// So: the statement's own example when the vectors carry it — the one input
// the whole page has been talking about — and the first case otherwise, which
// keeps every call on an input the Java and C++ gates already drive.
/** `nums = [1, 3, 6, 9], target = 12` → `[[1,3,6,9], 12]`, or null when the
 *  example is not written as `name = <literal>` pairs */
const exampleValues = (input) => {
  if (!input) return null
  const parts = input.split(/,\s*(?=[A-Za-z_]\w*\s*=)/)
  const values = []
  for (const part of parts) {
    const m = /^\s*[A-Za-z_]\w*\s*=\s*([\s\S]+?)\s*$/.exec(part)
    if (!m) return null
    try {
      values.push(
        JSON.parse(
          m[1]
            .replace(/\bTrue\b/g, "true")
            .replace(/\bFalse\b/g, "false")
            .replace(/\bNone\b/g, "null")
        )
      )
    } catch {
      return null
    }
  }
  return values
}
const same = (a, b) => JSON.stringify(a) === JSON.stringify(b)
const exampleOf = new Map(
  PROBLEMS.map((p) => [p.id, exampleValues(p.examples?.[0]?.input)])
)
let fromExample = 0

/** the parameter types this can render as a Python literal with no scaffolding */
const SIMPLE = new Set([
  "int",
  "float",
  "bool",
  "string",
  "int[]",
  "string[]",
  "int[][]",
  "char[]",
])

/** a JS value as Python source. JSON is Python for everything here except the
 *  three literals it spells differently. */
const py = (v) =>
  JSON.stringify(v)
    .replace(/\btrue\b/g, "True")
    .replace(/\bfalse\b/g, "False")
    .replace(/\bnull\b/g, "None")

/** a linked-list argument is a row of values, or {list, cycle} when the tail
 *  points back — cycle-detect's input is a SHAPE rather than a value */
const listArg = (v) =>
  Array.isArray(v)
    ? `__mklist(${py(v)})`
    : `__mklist(${py(v.list)}, ${v.cycle ?? -1})`

const arg = (v, t) =>
  t === "list" ? listArg(v) : t === "tree" ? `__mktree(${py(v)})` : py(v)

const demos = {}
for (const [id, spec] of Object.entries(VECTORS)) {
  // `shape: "class"` means the entry point is a class to instantiate against a
  // script of operations — a different driver, and not one appended line.
  if (spec.shape) continue
  if (!spec.params.every((t) => SIMPLE.has(t) || t === "list" || t === "tree"))
    continue
  const want = exampleOf.get(id)
  const matched = want && spec.cases?.find((c) => same(c, want))
  if (matched) fromExample++
  const chosen = matched ?? spec.cases?.[0]
  if (!chosen) continue
  demos[id] = chosen.map((v, i) => arg(v, spec.params[i])).join(", ")
}

const body = `// GENERATED by scripts/gen-demos.mjs — do not edit.
//
// One Python argument list per problem, from \`scripts/localsmith/vectors.mjs\`
// — the same inputs the differential runner drives every Java and C++ block
// with. The STATEMENT'S EXAMPLE where the vectors carry it, so Run answers the
// input the page has been talking about; the first case otherwise.
// ${fromExample} of ${Object.keys(demos).length} are the statement's example.
//
// The Run button on a code block appends \`print(<entry>(<these args>))\` when
// the block defines a function and calls nothing — which is every approach
// fence in every teaching document. Without it, Run defines a function and
// reports "the script printed nothing".
//
// ${Object.keys(demos).length} of ${Object.keys(VECTORS).length} problems are here. A linked list or a tree is built with the
// \`__mklist\` / \`__mktree\` that ride along in \`src/lib/py-preamble.ts\`. The
// rest are \`shape: "class"\` — a class to instantiate against a script of
// operations, which is not one appended line — and those blocks say so.
//
// \`src/data/demos.test.ts\` rebuilds this in memory and fails if it has drifted.

export const DEMOS: Record<string, string> = {
${Object.entries(demos)
  .map(([id, args]) => `  ${JSON.stringify(id)}: ${JSON.stringify(args)},`)
  .join("\n")}
}
`

if (check) {
  const lf = (s) => s.replace(/\r\n/g, "\n")
  let have = ""
  try {
    have = readFileSync(OUT, "utf8")
  } catch {
    /* absent counts as stale */
  }
  const stale = lf(have) !== lf(body)
  console.log(
    stale ? `${OUT} is stale — run node scripts/gen-demos.mjs` : `ok     ${OUT}`
  )
  process.exitCode = stale ? 1 : 0
} else {
  writeFileSync(OUT, body, "utf8")
  console.log(
    `wrote ${OUT}: ${Object.keys(demos).length} of ${Object.keys(VECTORS).length} problems can be called in one line`
  )
}
