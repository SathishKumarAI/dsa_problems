// Emit the two EAGER manifests: everything the shell needs before it knows
// which route it is on, and nothing else.
//
// The problem this solves, measured in a real browser on 2026-09-14:
//
//   first load of `#/`   747.1 KB over the wire, 9 files
//     567.7 KB   engine-*.js    <- all 93 journeys, generators and prose
//     107.8 KB   index-*.js
//
// Every journey and every problem record is reachable from the shell, so every
// one of them is in the first load. The shell does not need them. It needs a
// LIST: which problems exist, what they are called, which pattern they sit in,
// and — for the disclosure mask — which patterns each journey reveals and how
// many acts it has. That is a few tens of kilobytes. The rungs, the code in
// three languages, the frame generators and the teaching prose all belong to a
// route, and a route can fetch them.
//
// GENERATED, and committed, and guarded. Committed because `tsc` needs it and
// because a generated file that is not on disk breaks a fresh clone; guarded
// because a committed derivative is exactly what B72 had to undo — so
// `src/data/manifest.test.ts` rebuilds it in memory and fails if the checked-in
// copy disagrees. Run this when a problem or journey is added; `wire-batch.mjs`
// should call it.
//
// Run:  node scripts/gen-manifest.mjs
//       node scripts/gen-manifest.mjs --check   # exit 1 if stale, writes nothing

import { readFileSync, writeFileSync } from "node:fs"

const check = process.argv.includes("--check")

const { PROBLEMS, PATTERNS } = await import("../src/data/index.ts")
const { JOURNEYS } = await import("../src/engine/index.ts")

const q = (s) => JSON.stringify(s)

// ── problems ────────────────────────────────────────────────────────────────
// Fields chosen by what the eager surfaces actually read: the sidebar's counts,
// the pattern list's rows, the palette's index, the home grid. `statement`,
// `hints`, `constraints`, `examples`, `arc`, the three code blocks and every
// alternative are deliberately absent — they belong to the problem page.
const problems = PROBLEMS.map((p) => ({
  id: p.id,
  title: p.title,
  pattern: p.pattern,
  difficulty: p.difficulty,
  brief: p.brief,
  leetcode: p.leetcode,
}))

// ── journeys ────────────────────────────────────────────────────────────────
// `acts` is the COUNT, not the acts: `lib/disclosure.ts` needs it to decide
// whether a started journey is finished, and that is the only reason the whole
// engine was in the first chunk.
const journeys = JOURNEYS.map((j) => ({
  slug: j.slug,
  title: j.title,
  subtitle: j.subtitle,
  problemId: j.problemId,
  // The act LABELS — key, name and the four-word `short`. Not the acts.
  //
  // Home's dock says "next: Two speeds, nothing written down · constant space"
  // and links to `?act=<key>`, so it needs identity and a label eagerly. What it
  // does not need is the act's frame generator, its presets, its pseudocode, its
  // quiz or its three code tabs — which is everything else, and which is why
  // reading this off `JOURNEYS` cost 568 KB gzipped.
  //
  // Kept as an ARRAY rather than a count plus a parallel key list, so every
  // call site that already wrote `j.acts.length` or `j.acts[i].name` keeps
  // working and the diff stays honest. ~28 KB raw across 93 journeys.
  acts: j.acts.map((a) => ({ key: a.key, name: a.name, short: a.short })),
  reveals: j.reveals ?? [],
}))

const problemsFile = `// GENERATED by scripts/gen-manifest.mjs — do not edit.
//
// The eager half of the catalogue: what every surface needs before it knows
// which route it is on. The full \`Problem\` records live in
// \`src/data/problems/**\` and are fetched by the route that needs them.
//
// \`src/data/manifest.test.ts\` rebuilds this in memory and fails if it has
// drifted from the records, so this file cannot go stale in silence.

import type { Difficulty } from "./types.ts"

export interface ProblemCard {
  id: string
  title: string
  pattern: string
  difficulty: Difficulty
  brief: string
  leetcode: string
}

export const CATALOGUE: ProblemCard[] = [
${problems
  .map(
    (p) =>
      `  { id: ${q(p.id)}, title: ${q(p.title)}, pattern: ${q(p.pattern)}, difficulty: ${q(
        p.difficulty
      )}, brief: ${q(p.brief)}, leetcode: ${q(p.leetcode)} },`
  )
  .join("\n")}
]

export const cardOf = (id: string) => CATALOGUE.find((p) => p.id === id)
export const cardsOfPattern = (pattern: string) =>
  CATALOGUE.filter((p) => p.pattern === pattern)
`

const journeysFile = `// GENERATED by scripts/gen-manifest.mjs — do not edit.
//
// The eager half of the journey registry: enough to list them, count them, and
// run the disclosure mask — and NOT the acts, the frame generators, the presets
// or the code, which are 568 KB gzipped and belong to \`#/journey/<slug>\`.
//
// \`acts\` is the count rather than the acts for exactly one reason:
// \`lib/disclosure.ts\` compares the ledger against it to decide whether a
// started journey is finished, and that single number was holding the entire
// engine in the first chunk.

export interface ActCard {
  key: string
  name: string
  short: string
}

export interface JourneyCard {
  slug: string
  title: string
  subtitle: string
  problemId: string
  /** act labels in order — key, name, short. NOT the acts. */
  acts: ActCard[]
  /** pattern ids this journey withholds until its recap */
  reveals: string[]
}

export const JOURNEY_CARDS: JourneyCard[] = [
${journeys
  .map(
    (j) =>
      `  { slug: ${q(j.slug)}, title: ${q(j.title)}, subtitle: ${q(j.subtitle)}, problemId: ${q(
        j.problemId
      )}, acts: ${JSON.stringify(j.acts)}, reveals: ${JSON.stringify(j.reveals)} },`
  )
  .join("\n")}
]

export const cardBySlug = (slug: string) =>
  JOURNEY_CARDS.find((j) => j.slug === slug)
export const cardForProblem = (problemId: string) =>
  JOURNEY_CARDS.find((j) => j.problemId === problemId)
`

const targets = [
  ["src/data/manifest.ts", problemsFile],
  ["src/engine/manifest.ts", journeysFile],
]

let stale = 0
for (const [path, next] of targets) {
  let current = ""
  try {
    current = readFileSync(path, "utf8")
  } catch {
    current = ""
  }
  const same = current.replace(/\r\n/g, "\n") === next
  if (check) {
    if (!same) {
      console.error(`STALE  ${path}`)
      stale++
    } else console.log(`ok     ${path}`)
    continue
  }
  if (!same) writeFileSync(path, next, "utf8")
  console.log(`${same ? "unchanged" : "wrote    "}  ${path}`)
}

if (!check)
  console.log(
    `\n${problems.length} problems · ${journeys.length} journeys · ` +
      `${PATTERNS.length} patterns`
  )
if (check && stale) {
  console.error("\nrun: node scripts/gen-manifest.mjs")
  process.exit(1)
}
